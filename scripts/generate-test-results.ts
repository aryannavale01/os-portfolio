/**
 * Post-test script: reads the Playwright JSON reporter output and generates
 * E2E_TEST_RESULTS.md — a human-readable summary of the full test run.
 *
 * Usage:  npx tsx scripts/generate-test-results.ts
 *
 * Expects the JSON report at: test-results/results.json
 * (The Playwright config doesn't use JSON reporter by default — run with:
 *   npx playwright test --reporter=json,html
 * to generate both.)
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';

const REPORT_PATH = join(__dirname, '..', 'test-results', 'results.json');
const OUTPUT_PATH = join(__dirname, '..', 'E2E_TEST_RESULTS.md');

interface TestResult {
  status: 'passed' | 'failed' | 'timedOut' | 'skipped';
  expectedStatus: string;
  duration: number;
  error?: { message: string };
  attachments?: { name: string; path?: string }[];
}

interface SuiteSpec {
  title: string;
  file: string;
  specs: {
    title: string;
    ok: boolean;
    tests: { results: TestResult[] }[];
  }[];
}

interface JSONReport {
  suites: SuiteSpec[];
  stats: {
    expected: number;
    unexpected: number;
    flaky: number;
    skipped: number;
    duration: number;
  };
}

function formatDuration(ms: number): string {
  const s = Math.floor(ms / 1000);
  return s >= 60 ? `${Math.floor(s / 60)}m ${s % 60}s` : `${s}s`;
}

function main() {
  if (!existsSync(REPORT_PATH)) {
    console.error(
      `JSON report not found at ${REPORT_PATH}.\n` +
        'Run: npx playwright test --reporter=json,html'
    );
    process.exit(1);
  }

  const raw = readFileSync(REPORT_PATH, 'utf-8');
  const report: JSONReport = JSON.parse(raw);

  const passed = report.stats.expected;
  const failed = report.stats.unexpected;
  const flaky = report.stats.flaky;
  const skipped = report.stats.skipped;
  const total = passed + failed + flaky + skipped;

  const lines: string[] = [];
  lines.push('# E2E Test Results');
  lines.push('');
  lines.push(
    `**Run at:** ${new Date().toISOString()}  `
  );
  lines.push(
    `**Duration:** ${formatDuration(report.stats.duration)}`
  );
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(`| Metric | Count |`);
  lines.push(`|--------|-------|`);
  lines.push(`| Total  | ${total} |`);
  lines.push(`| Passed | ${passed} |`);
  lines.push(`| Failed | ${failed} |`);
  lines.push(`| Flaky  | ${flaky} |`);
  lines.push(`| Skipped | ${skipped} |`);
  lines.push('');

  // Collect failures
  const failures: { suite: string; test: string; error: string }[] = [];

  for (const suite of report.suites) {
    for (const spec of suite.specs) {
      const failing = spec.tests.find((t) =>
        t.results.some((r) => r.status === 'failed' || r.status === 'timedOut')
      );
      if (failing) {
        const result = failing.results.find(
          (r) => r.status === 'failed' || r.status === 'timedOut'
        );
        failures.push({
          suite: suite.title,
          test: spec.title,
          error:
            result?.error?.message?.slice(0, 300) ??
            'Unknown error',
        });
      }
    }
  }

  if (failures.length > 0) {
    lines.push('## Failing Tests');
    lines.push('');
    for (const f of failures) {
      lines.push(`### ${f.suite} > ${f.test}`);
      lines.push('');
      lines.push('```');
      lines.push(f.error);
      lines.push('```');
      lines.push('');
    }
  } else {
    lines.push('## All Tests Passed');
    lines.push('');
    lines.push('No failures detected.');
    lines.push('');
  }

  lines.push('---');
  lines.push(
    '*Generated by `scripts/generate-test-results.ts` from Playwright JSON output.*'
  );

  writeFileSync(OUTPUT_PATH, lines.join('\n'), 'utf-8');
  console.log(`Results written to ${OUTPUT_PATH}`);
}

main();
